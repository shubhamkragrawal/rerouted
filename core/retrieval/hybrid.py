"""Small, dependency-free BM25 + dense-hash + RRF retrieval implementation.

The hashing encoder is a deterministic fallback for tests and disconnected setup.
Production/local runs can inject embeddings generated by bge without changing the
ranking or temporal-filtering interface.
"""

from __future__ import annotations

import hashlib
import math
import re
from collections import Counter
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass
from datetime import date
from time import perf_counter
from typing import Literal, TypedDict

from .models import IndexedDocument
from .providers import (
    CrossEncoderProvider,
    EmbeddingMetadata,
    EmbeddingProvider,
    HashEmbeddingProvider,
    corpus_hash,
)

TOKEN_RE = re.compile(r"[a-z0-9]+(?:\.[a-z0-9]+)*")


def tokenize(text: str) -> list[str]:
    return TOKEN_RE.findall(text.lower())


def hashing_embedding(text: str, dimensions: int = 256) -> list[float]:
    vector = [0.0] * dimensions
    for token in tokenize(text):
        digest = hashlib.blake2b(token.encode("utf-8"), digest_size=8).digest()
        value = int.from_bytes(digest, "big")
        index = value % dimensions
        sign = 1.0 if (value >> 8) & 1 else -1.0
        vector[index] += sign
    norm = math.sqrt(sum(component * component for component in vector)) or 1.0
    return [component / norm for component in vector]


def cosine(left: Sequence[float], right: Sequence[float]) -> float:
    return sum(a * b for a, b in zip(left, right, strict=True))


@dataclass(frozen=True)
class RetrievalHit:
    document: IndexedDocument
    score: float
    rerank_score: float
    lexical_rank: int | None
    dense_rank: int | None


@dataclass(frozen=True)
class RetrievalReport:
    corpus_hash: str
    embedding_provider: str
    embedding_model_id: str
    embedding_model_version: str
    served_provider: str
    served_model_id: str
    served_model_version: str
    fallback_reason: str | None
    reranker_provider: str
    reranker_model_version: str | None
    candidate_count: int
    rerank_latency_ms: float
    excluded_by_date: int
    excluded_by_authority: int
    excluded_by_carrier: int
    excluded_by_jurisdiction: int


@dataclass(frozen=True)
class RetrievalResult:
    hits: list[RetrievalHit]
    report: RetrievalReport


class _BaseRetrievalReport(TypedDict):
    corpus_hash: str
    embedding_provider: str
    embedding_model_id: str
    embedding_model_version: str
    excluded_by_date: int
    excluded_by_authority: int
    excluded_by_carrier: int
    excluded_by_jurisdiction: int


class _CallableEmbeddingProvider:
    def __init__(self, embed: Callable[[str], Sequence[float]]) -> None:
        self.embed = embed
        self.metadata = EmbeddingMetadata(
            provider="custom",
            model_id=getattr(embed, "__qualname__", "custom-callable"),
            model_version="unspecified",
            pooling="custom",
            normalize=False,
            query_instruction="",
            document_instruction="",
        )

    def embed_query(self, text: str) -> Sequence[float]:
        return self.embed(text)

    def embed_documents(self, texts: Sequence[str]) -> Sequence[Sequence[float]]:
        return [self.embed(text) for text in texts]


class HybridRetriever:
    """Hybrid search with temporal filtering pushed before scoring."""

    def __init__(
        self,
        documents: Iterable[IndexedDocument],
        *,
        embed: Callable[[str], Sequence[float]] | None = None,
        embedding_provider: EmbeddingProvider | None = None,
        reranker: CrossEncoderProvider | None = None,
        rrf_constant: int = 60,
    ) -> None:
        self.documents = tuple(documents)
        if embedding_provider is not None and embed is not None:
            raise ValueError("pass either embed or embedding_provider, not both")
        self.embedding_provider = embedding_provider or (
            _CallableEmbeddingProvider(embed) if embed is not None else HashEmbeddingProvider()
        )
        self.reranker = reranker
        self.rrf_constant = rrf_constant
        self._embedding_cache: dict[str, Sequence[float]] = {}

    def search(
        self,
        query: str,
        *,
        as_of_date: date,
        k: int = 10,
        doc_types: set[str] | None = None,
        authority_types: set[str] | None = None,
        carrier: str | None = None,
        jurisdictions: set[str] | None = None,
        layer: Literal["obligation", "enforcement_policy"] = "obligation",
        candidate_limit: int = 50,
    ) -> tuple[list[RetrievalHit], int]:
        result = self.search_detailed(
            query,
            as_of_date=as_of_date,
            k=k,
            doc_types=doc_types,
            authority_types=authority_types,
            carrier=carrier,
            jurisdictions=jurisdictions,
            layer=layer,
            candidate_limit=candidate_limit,
        )
        return result.hits, result.report.excluded_by_date

    def search_detailed(
        self,
        query: str,
        *,
        as_of_date: date,
        k: int = 10,
        doc_types: set[str] | None = None,
        authority_types: set[str] | None = None,
        carrier: str | None = None,
        jurisdictions: set[str] | None = None,
        layer: Literal["obligation", "enforcement_policy"] = "obligation",
        candidate_limit: int = 50,
    ) -> RetrievalResult:
        """Return ranked hits with explicit provider, fallback, and filter diagnostics."""
        if k < 0 or candidate_limit < 1:
            raise ValueError("k must be non-negative and candidate_limit must be positive")
        eligible: list[IndexedDocument] = []
        excluded_by_date = 0
        excluded_by_authority = 0
        excluded_by_carrier = 0
        excluded_by_jurisdiction = 0
        for document in self.documents:
            if doc_types and document.doc_type not in doc_types:
                continue
            is_policy = (
                document.authority == "enforcement_policy"
                or document.doc_type == "enforcement_policy"
            )
            if (layer == "enforcement_policy") != is_policy:
                excluded_by_authority += 1
                continue
            if authority_types and document.authority not in authority_types:
                excluded_by_authority += 1
                continue
            if carrier and document.carrier not in (None, carrier):
                excluded_by_carrier += 1
                continue
            jurisdiction = document.jurisdiction or document.metadata.get("jurisdiction")
            if jurisdictions and jurisdiction not in jurisdictions:
                excluded_by_jurisdiction += 1
                continue
            if not document.active_on(as_of_date):
                excluded_by_date += 1
                continue
            eligible.append(document)

        metadata = self.embedding_provider.metadata
        base_report: _BaseRetrievalReport = {
            "corpus_hash": corpus_hash(self.documents),
            "embedding_provider": metadata.provider,
            "embedding_model_id": metadata.model_id,
            "embedding_model_version": metadata.model_version,
            "excluded_by_date": excluded_by_date,
            "excluded_by_authority": excluded_by_authority,
            "excluded_by_carrier": excluded_by_carrier,
            "excluded_by_jurisdiction": excluded_by_jurisdiction,
        }
        if not eligible:
            return RetrievalResult(
                [],
                RetrievalReport(
                    **base_report,
                    served_provider=metadata.provider,
                    served_model_id=metadata.model_id,
                    served_model_version=metadata.model_version,
                    fallback_reason=None,
                    reranker_provider=(
                        self.reranker.model_id if self.reranker else "lexical-overlap"
                    ),
                    reranker_model_version=self.reranker.model_version if self.reranker else None,
                    candidate_count=0,
                    rerank_latency_ms=0.0,
                ),
            )

        lexical = self._bm25(query, eligible)[:candidate_limit]
        fallback_reason: str | None = None
        served_provider = metadata.provider
        served_model_id = metadata.model_id
        served_model_version = metadata.model_version
        try:
            dense = self._dense(query, eligible)[:candidate_limit]
        except Exception as exc:
            fallback_reason = f"{type(exc).__name__}: {exc}"
            fallback_provider = HashEmbeddingProvider()
            dense = self._dense_with_provider(query, eligible, fallback_provider)[:candidate_limit]
            served_provider = fallback_provider.metadata.provider
            served_model_id = fallback_provider.metadata.model_id
            served_model_version = fallback_provider.metadata.model_version
        lexical_rank = {index: rank for rank, (index, _) in enumerate(lexical, 1)}
        dense_rank = {index: rank for rank, (index, _) in enumerate(dense, 1)}

        fused: list[tuple[int, float]] = []
        for index in set(lexical_rank) | set(dense_rank):
            score = 0.0
            if index in lexical_rank:
                score += 1.0 / (self.rrf_constant + lexical_rank[index])
            if index in dense_rank:
                score += 1.0 / (self.rrf_constant + dense_rank[index])
            fused.append((index, score))
        fused.sort(key=lambda item: (-item[1], eligible[item[0]].document_id))

        hits: list[RetrievalHit] = []
        for index, score in fused[:candidate_limit]:
            hits.append(
                RetrievalHit(
                    document=eligible[index],
                    score=score,
                    rerank_score=score,
                    lexical_rank=lexical_rank.get(index),
                    dense_rank=dense_rank.get(index),
                )
            )
        rerank_started = perf_counter()
        reranker_provider = self.reranker.model_id if self.reranker else "lexical-overlap"
        reranker_version = self.reranker.model_version if self.reranker else None
        if self.reranker is not None:
            try:
                scores = self.reranker.score(query, [hit.document.text for hit in hits])
                if len(scores) != len(hits):
                    raise ValueError("cross-encoder returned a score count mismatch")
                hits = [
                    RetrievalHit(
                        document=hit.document,
                        score=hit.score,
                        rerank_score=float(score),
                        lexical_rank=hit.lexical_rank,
                        dense_rank=hit.dense_rank,
                    )
                    for hit, score in zip(hits, scores, strict=True)
                ]
            except Exception as exc:
                reranker_error = f"reranker: {type(exc).__name__}: {exc}"
                fallback_reason = "; ".join(
                    filter(None, [fallback_reason, reranker_error])
                )
                reranker_provider = "rrf"
                reranker_version = None
                hits = [
                    RetrievalHit(
                        hit.document,
                        hit.score,
                        hit.score,
                        hit.lexical_rank,
                        hit.dense_rank,
                    )
                    for hit in hits
                ]
        else:
            query_terms = set(tokenize(query))
            hits = [
                RetrievalHit(
                    hit.document,
                    hit.score,
                    hit.score
                    + len(query_terms & set(tokenize(hit.document.text)))
                    / max(1, len(query_terms)),
                    hit.lexical_rank,
                    hit.dense_rank,
                )
                for hit in hits
            ]
        hits.sort(key=lambda hit: (-hit.rerank_score, hit.document.document_id))
        report = RetrievalReport(
            **base_report,
            served_provider=served_provider,
            served_model_id=served_model_id,
            served_model_version=served_model_version,
            fallback_reason=fallback_reason,
            reranker_provider=reranker_provider,
            reranker_model_version=reranker_version,
            candidate_count=len(hits),
            rerank_latency_ms=(perf_counter() - rerank_started) * 1000,
        )
        return RetrievalResult(hits[:k], report)

    @staticmethod
    def _bm25(query: str, documents: Sequence[IndexedDocument]) -> list[tuple[int, float]]:
        tokenized = [tokenize(document.text) for document in documents]
        query_tokens = tokenize(query)
        average_length = sum(map(len, tokenized)) / max(1, len(tokenized))
        document_frequency: Counter[str] = Counter()
        for tokens in tokenized:
            document_frequency.update(set(tokens))

        scored: list[tuple[int, float]] = []
        for index, tokens in enumerate(tokenized):
            frequencies = Counter(tokens)
            score = 0.0
            for term in query_tokens:
                frequency = frequencies[term]
                if not frequency:
                    continue
                count = document_frequency[term]
                inverse_frequency = math.log(1 + (len(documents) - count + 0.5) / (count + 0.5))
                length_norm = frequency + 1.5 * (
                    1 - 0.75 + 0.75 * len(tokens) / max(1.0, average_length)
                )
                score += inverse_frequency * frequency * 2.5 / length_norm
            scored.append((index, score))
        return sorted(scored, key=lambda item: (-item[1], documents[item[0]].document_id))

    def _dense(self, query: str, documents: Sequence[IndexedDocument]) -> list[tuple[int, float]]:
        return self._dense_with_provider(query, documents, self.embedding_provider)

    def _dense_with_provider(
        self,
        query: str,
        documents: Sequence[IndexedDocument],
        provider: EmbeddingProvider,
    ) -> list[tuple[int, float]]:
        query_vector = provider.embed_query(query)
        metadata = provider.metadata
        vectors: list[Sequence[float]] = []
        missing: list[IndexedDocument] = []
        missing_keys: list[str] = []
        for document in documents:
            key = metadata.cache_key(document)
            cached = self._embedding_cache.get(key) if provider is self.embedding_provider else None
            if cached is None:
                missing.append(document)
                missing_keys.append(key)
                vectors.append(())
            else:
                vectors.append(cached)
        if missing:
            encoded = provider.embed_documents([document.text for document in missing])
            if len(encoded) != len(missing):
                raise ValueError("embedding provider returned a vector count mismatch")
            missing_vectors = list(encoded)
            missing_position = 0
            for index, vector in enumerate(vectors):
                if not vector:
                    vectors[index] = missing_vectors[missing_position]
                    if provider is self.embedding_provider:
                        self._embedding_cache[missing_keys[missing_position]] = vectors[index]
                    missing_position += 1
        scored = [(index, cosine(query_vector, vector)) for index, vector in enumerate(vectors)]
        return sorted(scored, key=lambda item: (-item[1], documents[item[0]].document_id))
